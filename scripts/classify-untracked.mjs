/**
 * Untracked-file classifier.
 *
 * Specification §4.3 requires every untracked item to be classified before any
 * commit — as required source, test, configuration, documentation/release
 * evidence, generated output, cache, log, temporary file, model weight, secret,
 * or unknown-needing-inspection. §15.1 is emphatic that `git add -A` must never
 * be the first move on a tree with hundreds of untracked paths.
 *
 * Classifying them needs no device, credential or toolchain, so this was never
 * externally blocked — it was simply never done.
 *
 * The output is the pre-commit worksheet: what is safe to stage, what must be
 * ignored, and what a human still has to look at.
 *
 * Usage: node scripts/classify-untracked.mjs [--json]
 * Exit:  0 normally; 1 if anything lands in `secret` or `unknown`, because both
 *        require a human decision before the tree can be committed.
 */

import { execFileSync } from "node:child_process";
import { statSync, readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/** Content that would be a credential if it appeared in a file. */
const SECRET_SHAPE =
  /sk-[A-Za-z0-9_-]{20,}|AKIA[0-9A-Z]{16}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\./;

/** Ordered rules — first match wins. */
const RULES = [
  { kind: "secret", why: "environment file", re: /(^|\/)\.env(\.|$)/ },
  {
    kind: "secret",
    why: "key or certificate",
    re: /\.(pem|key|p12|pfx|keystore|jks|mobileprovision)$/i,
  },
  { kind: "model-weight", why: "model weights", re: /\.(gguf|safetensors|onnx|bin)$/i },
  {
    kind: "generated",
    why: "build output",
    re: /(^|\/)(dist|build|\.output|\.nitro|\.vinxi|coverage|target)\//,
  },
  { kind: "generated", why: "dependency tree", re: /(^|\/)node_modules\// },
  { kind: "generated", why: "generated route tree", re: /routeTree\.gen\.ts$/ },
  {
    kind: "cache",
    why: "cache directory",
    re: /(^|\/)(\.cache|\.turbo|\.parcel-cache|\.eslintcache)(\/|$)/,
  },
  { kind: "log", why: "log file", re: /\.log$/i },
  { kind: "temp", why: "temporary file", re: /\.(tmp|temp|swp|orig|rej)$|~$/i },
  { kind: "test", why: "test file", re: /(^|\/)__tests__\/|\.(test|spec)\.[cm]?[jt]sx?$/ },
  {
    kind: "source",
    why: "application source",
    re: /^(src|relay|extension|native|android|ios|mobile)\/.*\.(ts|tsx|js|jsx|mjs|cjs|rs|java|kt|swift|css|html)$/,
  },
  // Android/iOS platform files. Generated by the Capacitor toolchain but
  // CHECKED IN, because they carry hand-edited settings (permissions, network
  // security config, signing config) that must not be silently regenerated.
  {
    kind: "platform-config",
    why: "Android/iOS platform configuration",
    re: /^(android|ios)\/.*\.(gradle|pro|xml|plist|pbxproj|xcscheme|xcworkspacedata|properties|entitlements)$/i,
  },
  {
    kind: "platform-config",
    why: "Gradle wrapper or build script",
    re: /^android\/(gradlew|gradlew\.bat|gradle\/)/,
  },
  // Interface Builder files and Xcode build settings are hand-edited iOS
  // source; the Tauri entitlements plist lives under native/, not ios/.
  { kind: "platform-config", why: "iOS storyboard", re: /\.storyboard$/i },
  { kind: "platform-config", why: "Xcode build settings", re: /\.xcconfig$/i },
  {
    kind: "platform-config",
    why: "macOS/iOS entitlements",
    re: /(^|\/)entitlements\.plist$|\.entitlements$/i,
  },
  { kind: "migration", why: "database migration or safety SQL", re: /^supabase\/.*\.sql$/ },
  {
    kind: "config",
    why: "configuration",
    re: /^(\.github\/|\.vscode\/)|(^|\/)(package\.json|tsconfig.*\.json|vite\.config\.[cm]?[jt]s|vitest\.config\.[cm]?[jt]s|eslint\.config\.[cm]?[jt]s|docker-compose\.ya?ml|Dockerfile|capacitor\.config\.json|wrangler\.json|Cargo\.toml|Cargo\.lock|\.gitignore)$/,
  },
  { kind: "config", why: "configuration file", re: /\.(json|ya?ml|toml|conf|ini)$/i },
  { kind: "script", why: "automation script", re: /^scripts\/.*\.[cm]?js$/ },
  // The requirement-register audit pipeline lives under `audit/`, not
  // `scripts/`, and emits newline-delimited JSON. Neither the `script` rule
  // (anchored to `^scripts/`) nor the config rule (`\.json$` does not match
  // `.jsonl`) reaches it, so both fell through to `unknown` and blocked the
  // gate. Both replacements stay anchored to `^audit/` so this remains a narrow
  // rule for one known directory and never degrades into a catch-all — a path
  // outside `audit/` with the same extension must still demand a human.
  { kind: "script", why: "audit pipeline script", re: /^audit\/.*\.[cm]?js$/ },
  { kind: "docs", why: "retained audit evidence", re: /^audit\/.*\.jsonl$/ },
  {
    kind: "docs",
    why: "documentation or release evidence",
    re: /^(release|docs|\.claude)\/|\.mdx?$/i,
  },
  {
    kind: "asset",
    why: "static asset",
    re: /\.(png|jpe?g|svg|gif|webp|ico|woff2?|ttf|otf|mp4|webm)$/i,
  },
];

function bytesOf(path) {
  try {
    return statSync(path).size;
  } catch {
    return 0;
  }
}

/** Cheap secret sniff for small text files only. */
function looksSecret(path, size) {
  if (size > 512 * 1024) return false;
  if (!/\.(ts|tsx|js|mjs|cjs|json|ya?ml|md|sql|txt|env|sh|ps1)$/i.test(path)) return false;
  try {
    return SECRET_SHAPE.test(readFileSync(path, "utf8"));
  } catch {
    return false;
  }
}

/**
 * Classify ONE path. Exported so the rules can be tested directly against
 * synthetic paths — the tree's own untracked set is not a fixture, and once it
 * is fully committed (which is the goal) it is empty, so report-driven tests
 * alone would silently stop asserting anything.
 *
 * `sniff` is injected so a caller can classify a path that does not exist on
 * disk; it defaults to the real content check.
 */
export function classifyPath(path, size = bytesOf(path), sniff = looksSecret) {
  for (const rule of RULES) {
    if (rule.re.test(path)) {
      // A file that looks like source but CONTAINS a credential is a secret
      // first. Path shape must never override content.
      if (rule.kind !== "secret" && sniff(path, size)) {
        // ...with one honest exception. A TEST asserting that a redactor or
        // scanner catches `sk-…` must contain a credential-SHAPED string, or it
        // is asserting nothing. Those are synthetic fixtures and must be
        // staged. They are still surfaced separately rather than waved through,
        // so a real key committed inside a test cannot hide behind this rule.
        if (rule.kind === "test") {
          return {
            path,
            kind: "test-fixture",
            why: "test contains credential-SHAPED fixtures (synthetic) — review, then stage",
            bytes: size,
          };
        }
        return { path, kind: "secret", why: "credential-shaped content", bytes: size };
      }
      return { path, kind: rule.kind, why: rule.why, bytes: size };
    }
  }
  const secret = sniff(path, size);
  return {
    path,
    kind: secret ? "secret" : "unknown",
    why: secret ? "credential-shaped content" : "no rule matched — needs inspection",
    bytes: size,
  };
}

/** Classify the whole untracked set. Exported for tests. */
export function classifyUntracked(paths) {
  return paths.map((p) => classifyPath(p));
}

/** Read the untracked set from git. Side-effecting, so it stays out of import. */
function readUntracked() {
  return execFileSync("git", ["ls-files", "--others", "--exclude-standard"], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  })
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
}

/** What each class means for staging. */
const DISPOSITION = {
  source: "STAGE — application source",
  test: "STAGE — test",
  config: "STAGE — configuration",
  script: "STAGE — automation script",
  migration: "STAGE — migration / safety SQL",
  docs: "STAGE — documentation and release evidence",
  asset: "STAGE — static asset",
  generated: "DO NOT STAGE — regenerated by a build",
  cache: "DO NOT STAGE — cache",
  log: "DO NOT STAGE — log",
  temp: "DO NOT STAGE — temporary",
  "model-weight": "DO NOT STAGE — model weights belong outside git",
  secret: "NEVER STAGE — inspect and remove",
  "platform-config": "STAGE — Android/iOS platform configuration",
  "test-fixture": "STAGE after review — synthetic credential-shaped fixtures",
  unknown: "INSPECT — a human must classify this",
};

/** Build the full report from a classified set. Exported for tests. */
export function buildReport(classified) {
  const groups = classified.reduce((acc, f) => {
    (acc[f.kind] ??= []).push(f);
    return acc;
  }, {});
  const needsHuman = [...(groups.secret ?? []), ...(groups.unknown ?? [])];
  return {
    generatedAt: new Date().toISOString(),
    total: classified.length,
    counts: Object.fromEntries(Object.entries(groups).map(([k, v]) => [k, v.length])),
    needsHuman: needsHuman.map((f) => ({ path: f.path, kind: f.kind, why: f.why })),
    files: classified,
    groups,
  };
}

// CLI. Guarded so importing this module for tests never shells out to git,
// prints, or exits the test runner.
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  const jsonOnly = process.argv.includes("--json");
  const classified = classifyUntracked(readUntracked());
  const { groups, ...report } = buildReport(classified);
  const needsHuman = report.needsHuman;

  if (jsonOnly) {
    console.log(JSON.stringify(report, null, 2));
  } else {
    console.log(`Untracked classification: ${classified.length} paths\n`);
    for (const [kind, files] of Object.entries(groups).sort((a, b) => b[1].length - a[1].length)) {
      console.log(`  ${String(files.length).padStart(4)}  ${kind.padEnd(13)} ${DISPOSITION[kind]}`);
    }
    if (needsHuman.length > 0) {
      console.log(`\n  ${needsHuman.length} path(s) need a human decision before any commit:`);
      for (const f of needsHuman.slice(0, 40))
        console.log(`    ${f.kind.padEnd(8)} ${f.path} — ${f.why}`);
      if (needsHuman.length > 40)
        console.log(`    …and ${needsHuman.length - 40} more (use --json)`);
    } else if (classified.length === 0) {
      console.log("\n  Nothing untracked — the tree is fully committed.");
    } else {
      console.log("\n  Every untracked path is classified. None is a secret or unknown.");
    }
  }

  process.exit(needsHuman.length === 0 ? 0 : 1);
}
