/**
 * NAME THE CHUNKS THE SERVICE WORKER CANNOT KNOW.
 *
 * `public/sw.js` deliberately does not list the JavaScript bundles, and its
 * comment gives the reason: they are content-hashed, so a hard-coded list goes
 * stale on the next build. Correct — and the consequence was that it never
 * cached them at all.
 *
 * The runtime cache picks up an asset AFTER it has been fetched through the
 * worker. On a first visit the worker is installing while the page's own
 * scripts are already in flight, so those requests never pass through it.
 * Anybody who visited once and then went offline got the cached shell document
 * with none of its JavaScript: a page with the right title, the right favicon,
 * and nothing in the body. The offline promise failed for exactly the person
 * it was written for.
 *
 * So the list IS generated, once per build, from the entry chunk's own static
 * import graph — the same walk the asset budget uses to decide what a visitor
 * waits for before first paint. Lazy routes are not included: they are lazy on
 * purpose, and precaching them would put megabytes into the install step.
 *
 * The output is a separate file rather than a rewrite of sw.js, so the worker
 * stays readable source that a person can audit, and a build that skips this
 * step degrades to the old behaviour instead of breaking.
 */
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { join } from "node:path";

const publicDir = process.argv[2] ?? ".output/public";
const assetsDir = join(publicDir, "assets");

let entries;
try {
  entries = await readdir(assetsDir);
} catch {
  console.error(`No assets directory at ${assetsDir}. Build first.`);
  process.exit(2);
}

const names = new Set(entries);

/** Static `import … from "./chunk.js"` only — a dynamic import is lazy. */
function staticImportsOf(source) {
  const found = new Set();
  const pattern = /(?:^|[;\s])import\s*(?:[^'"()]*?from\s*)?["']\.\/([^"']+)["']/g;
  let match;
  while ((match = pattern.exec(source))) found.add(match[1]);
  return found;
}

const entryChunks = entries.filter((name) => /^index-.*\.js$/.test(name));
if (entryChunks.length === 0) {
  console.error("No entry chunk (index-*.js) found — refusing to write an empty precache list.");
  process.exit(2);
}

const reachable = new Set(entryChunks);
const walk = [...entryChunks];
while (walk.length > 0) {
  const name = walk.pop();
  let source;
  try {
    source = await readFile(join(assetsDir, name), "utf8");
  } catch {
    continue;
  }
  for (const dependency of staticImportsOf(source)) {
    if (names.has(dependency) && !reachable.has(dependency)) {
      reachable.add(dependency);
      walk.push(dependency);
    }
  }
}

// Stylesheets are not imported by the JS graph in a way the walk above sees,
// and a page with no CSS is as unusable as a page with no JS.
for (const name of entries) if (name.endsWith(".css")) reachable.add(name);

const urls = [...reachable].sort().map((name) => `/assets/${name}`);
let bytes = 0;
for (const name of reachable) {
  try {
    bytes += (await stat(join(assetsDir, name))).size;
  } catch {
    /* Listed but unreadable: the worker treats every entry as optional. */
  }
}

const output = join(publicDir, "sw-precache.js");
await writeFile(
  output,
  `/* Generated by scripts/generate-sw-precache.mjs — do not edit. */\n` +
    `self.__OCADE_PRECACHE = ${JSON.stringify(urls, null, 2)};\n`,
  "utf8",
);

console.log(
  `sw-precache: ${urls.length} first-paint assets, ${(bytes / 1024).toFixed(1)} KiB -> ${output}`,
);
