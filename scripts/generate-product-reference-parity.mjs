/** Generate PLAN.md §3's dated current-reference parity ledger. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { format, resolveConfig } from "prettier";
import {
  PRODUCT_REFERENCE_PARITY,
  validateProductReferenceParity,
} from "../src/lib/release/product-reference-parity.ts";

const CHECK = process.argv.includes("--check");
const DIRECTORY = join("docs", "product-reference");
const JSON_PATH = join(DIRECTORY, "OCADE_REFERENCE_PARITY.json");
const MARKDOWN_PATH = join(DIRECTORY, "OCADE_REFERENCE_PARITY.md");
const prettierConfig = (await resolveConfig(JSON_PATH)) ?? {};

const problems = validateProductReferenceParity(PRODUCT_REFERENCE_PARITY, existsSync);
if (problems.length) {
  console.error("The current-reference parity authority is invalid:");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const count = (field, value) =>
  PRODUCT_REFERENCE_PARITY.filter((item) => item[field] === value).length;
const summary = {
  total: PRODUCT_REFERENCE_PARITY.length,
  chat: count("referenceProduct", "chat"),
  cowork: count("referenceProduct", "cowork"),
  code: count("referenceProduct", "code"),
  team: count("referenceProduct", "team"),
  enterprise: count("referenceProduct", "enterprise"),
  missing: count("implementationState", "missing"),
  partial: count("implementationState", "partial"),
  complete: count("implementationState", "complete"),
};

const document = {
  schemaVersion: 1,
  generatedBy: "scripts/generate-product-reference-parity.mjs",
  source: "src/lib/release/product-reference-parity.ts",
  authority: "PLAN.md §3",
  evidenceBoundary:
    "Public documentation is a behavioral reference only. This ledger does not copy source, prompts, private APIs, branding, assets, layouts, or trade dress.",
  summary,
  capabilities: PRODUCT_REFERENCE_PARITY,
};
const jsonText = await format(JSON.stringify(document), {
  ...prettierConfig,
  parser: "json",
});

const escape = (value) => String(value).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const markdownText = await format(
  [
    "# OCADE current-reference parity",
    "",
    "> Generated from the typed authority. Do not edit this file by hand.",
    "> `npm run parity:check` refuses stale JSON or Markdown.",
    "",
    `Checked against dated official public documentation: **${PRODUCT_REFERENCE_PARITY[0]?.sourceCheckedAt ?? "unknown"}**.`,
    "",
    "This is a behavioral reference only. It does not import Anthropic source, prompts, private APIs, branding, assets, layouts, or trade dress.",
    "",
    "## Summary",
    "",
    "| Scope | Count |",
    "| --- | ---: |",
    `| Chat | ${summary.chat} |`,
    `| Cowork | ${summary.cowork} |`,
    `| Code | ${summary.code} |`,
    `| Team | ${summary.team} |`,
    `| Enterprise | ${summary.enterprise} |`,
    `| **Total** | **${summary.total}** |`,
    "",
    "| OCADE state | Count |",
    "| --- | ---: |",
    `| Missing | ${summary.missing} |`,
    `| Partial | ${summary.partial} |`,
    `| Complete | ${summary.complete} |`,
    "",
    "## Capability ledger",
    "",
    "| ID | Reference | Capability | Disposition | State | OCADE authority | Official source |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...PRODUCT_REFERENCE_PARITY.map(
      (item) =>
        `| ${item.id} | ${item.referenceProduct} | ${escape(item.capability)} | ${item.disposition} | ${item.implementationState} | ${item.currentOcadeAuthority ? `\`${item.currentOcadeAuthority}\`` : "—"} | [official documentation](${item.documentedSource}) |`,
    ),
    "",
    "## Required proof",
    "",
    ...PRODUCT_REFERENCE_PARITY.flatMap((item) => [
      `### ${item.id}`,
      "",
      `- Reason: ${item.reason}`,
      `- Surfaces: ${item.requiredSurfaces.join(", ")}`,
      `- Required tests: ${item.requiredTests.map((path) => `\`${path}\``).join(", ") || "none"}`,
      `- Evidence: ${item.evidence.map((path) => `\`${path}\``).join(", ") || "none yet"}`,
      "",
    ]),
  ].join("\n"),
  { ...prettierConfig, parser: "markdown" },
);

const outputs = [
  [JSON_PATH, jsonText],
  [MARKDOWN_PATH, markdownText],
];

if (CHECK) {
  const stale = outputs
    .filter(([path, expected]) => !existsSync(path) || readFileSync(path, "utf8") !== expected)
    .map(([path]) => path);
  if (stale.length) {
    console.error(`Current-reference parity output is stale: ${stale.join(", ")}`);
    console.error("Run `npm run parity:generate`.");
    process.exit(1);
  }
  console.log(`Current-reference parity current: ${summary.total} documented capabilities.`);
} else {
  mkdirSync(DIRECTORY, { recursive: true });
  for (const [path, content] of outputs) writeFileSync(path, content, "utf8");
  console.log(`Wrote current-reference parity: ${summary.total} documented capabilities.`);
}
