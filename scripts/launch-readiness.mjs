#!/usr/bin/env node
/**
 * Commercial launch readiness (plan.md 214-234), computed only from
 * evidence/readiness/gates.json: a milestone earns 10 points when every condition
 * is PASS and every cited evidence file exists. Fails on an unknown status, a PASS
 * without evidence, a missing evidence file, or a non-PASS without a reason
 * (UNTESTED excepted). Writes evidence/readiness/READINESS.md with the commit SHA.
 *
 *   node scripts/launch-readiness.mjs [--write]
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const STATES = ["PASS", "PARTIAL", "FAIL", "BLOCKED", "UNTESTED"];
const { milestones } = JSON.parse(readFileSync("evidence/readiness/gates.json", "utf8"));
const problems = [];
const conditions = milestones.flatMap((m) => m.conditions.map((c) => ({ ...c, milestone: m.n })));
for (const c of conditions) {
  const where = `milestone ${c.milestone} ${c.id}`;
  if (!STATES.includes(c.status)) problems.push(`${where}: unknown status ${c.status}`);
  if (c.status === "PASS" && !c.evidence.length) problems.push(`${where}: PASS without evidence`);
  for (const path of c.evidence) if (!existsSync(path)) problems.push(`${where}: missing ${path}`);
  if (!["PASS", "UNTESTED"].includes(c.status) && !c.reason) problems.push(`${where}: no reason`);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const earned = milestones.filter((m) => m.conditions.every((c) => c.status === "PASS"));
const count = (status) => conditions.filter((c) => c.status === status).length;
const passed = count("PASS");
const score = earned.length * 10;
const progress = Math.round((passed / conditions.length) * 1000) / 10;
const sha = execSync("git rev-parse --short HEAD").toString().trim();
const summary =
  `Readiness ${score}% earned (${earned.length}/10 milestones) | conditions PASS ${passed}/${conditions.length} ` +
  `(${progress}%), remaining ${Math.round((100 - progress) * 10) / 10}% | PARTIAL ${count("PARTIAL")}, ` +
  `FAIL ${count("FAIL")}, BLOCKED ${count("BLOCKED")}, UNTESTED ${count("UNTESTED")} | ${sha}`;
console.log(summary);

if (process.argv.includes("--write")) {
  const rows = milestones.map((m) => {
    const ok = m.conditions.filter((c) => c.status === "PASS").length;
    const lines = m.conditions.map(
      (c) =>
        `  - **${c.status}** ${c.text}${c.reason ? ` (${c.reason})` : ""}${c.evidence.length ? ` [${c.evidence.join(", ")}]` : ""}`,
    );
    return [`- **${m.n * 10}% ${m.name}**: ${ok}/${m.conditions.length} PASS`, ...lines].join("\n");
  });
  writeFileSync(
    "evidence/readiness/READINESS.md",
    `# Commercial launch readiness\n\nGenerated by \`node scripts/launch-readiness.mjs --write\` from ` +
      `\`evidence/readiness/gates.json\` on ${new Date().toISOString().slice(0, 10)} at commit \`${sha}\`.\n\n` +
      `**${summary}**\n\nA milestone earns its 10% only when every condition passes with evidence. ` +
      `The condition share is work verified, not a success probability.\n\n${rows.join("\n")}\n`,
  );
}
