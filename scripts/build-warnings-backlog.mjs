/**
 * Regenerate WARNINGS_BACKLOG.md from a real ESLint run.
 *
 * Self-contained on purpose: it runs ESLint itself rather than reading a report
 * someone left lying around, so the backlog can never quietly describe a state
 * the code has moved on from.
 *
 * Only warnings with no safe automatic fix should survive to this file. Run
 * `npx eslint . --fix` first; anything auto-fixable will disappear and what
 * remains is the genuine backlog.
 *
 * Usage: node scripts/build-warnings-backlog.mjs
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = "WARNINGS_BACKLOG.md";

/**
 * What it would actually take to fix each rule. Written per-rule because
 * "231 warnings" is not actionable and a bare count invites the worst possible
 * response, which is suppressing them.
 */
const NOTES = {
  "@typescript-eslint/no-explicit-any":
    "Each `any` needs a real type written by someone who knows what the value actually is. There is no safe automatic fix: replacing `any` with `unknown` compiles but pushes the error to every call site, and inferring a type from usage guesses at intent. Fix per-file alongside a change to that file, not in a sweep.",
  "react-refresh/only-export-components":
    "The file exports both a component and something else, which breaks fast refresh during development. Fixing means moving the non-component export to its own module — a real refactor with import churn across callers, and no behaviour change to show for it. Worth doing when the file is next touched.",
  "react-hooks/exhaustive-deps":
    "A hook's dependency array is missing a value it reads. Adding it automatically is NOT safe: it can turn a mount-only effect into one that re-runs on every render, causing loops or duplicate requests. Each needs a human decision about whether the effect should re-run, or whether the value should be a ref.",
  "(unused eslint-disable directive)":
    "A suppression comment that no longer suppresses anything. Safe to delete, but only after confirming the underlying rule is genuinely clean rather than disabled elsewhere.",
};

/** Files owned by the three products bundled alongside OCADE. */
const OTHER_PRODUCT_FILE =
  /(^|\/)(ficia|cania|madee|messenger|india-calculators|country-packs|timesheet)[.\-/]/i;

// Run ESLint's own entry point under this Node process.
//
// `shell: true` was the first attempt and is wrong: with a shell, arguments are
// concatenated rather than escaped, which is what Node's DEP0190 warns about.
// Naming `npx.cmd` was the second attempt and is also wrong: Node 24 refuses to
// spawn .cmd files without a shell (EINVAL), so it trades a security warning
// for a hard failure. Invoking the JS entry directly avoids the shell, the
// platform-specific wrapper, and PATH resolution altogether.
const eslintBin = fileURLToPath(new URL("../node_modules/eslint/bin/eslint.js", import.meta.url));

let raw;
try {
  raw = execFileSync(process.execPath, [eslintBin, ".", "--format", "json"], {
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024,
  });
} catch (error) {
  // ESLint exits non-zero when it reports problems, which is the normal case
  // here — the report is still on stdout.
  raw = error.stdout;
  if (!raw) throw error;
}

const report = JSON.parse(raw);
const cwd = process.cwd();
const byRule = new Map();
let errors = 0;

for (const file of report) {
  const rel = file.filePath.replace(cwd, "").replace(/\\/g, "/").replace(/^\//, "");
  for (const message of file.messages) {
    if (message.severity !== 1) {
      errors += 1;
      continue;
    }
    const rule = message.ruleId ?? "(unused eslint-disable directive)";
    if (!byRule.has(rule)) byRule.set(rule, new Map());
    const files = byRule.get(rule);
    if (!files.has(rel)) files.set(rel, []);
    files.get(rel).push(message.line);
  }
}

const countOf = (files) => [...files.values()].reduce((n, l) => n + l.length, 0);
const total = [...byRule.values()].reduce((n, files) => n + countOf(files), 0);

let otherProduct = 0;
let ocade = 0;
for (const [, files] of byRule) {
  for (const [file, ls] of files) {
    if (OTHER_PRODUCT_FILE.test(file)) otherProduct += ls.length;
    else ocade += ls.length;
  }
}

const lines = [
  "# Lint Warnings Backlog",
  "",
  "Warnings with **no safe automatic fix**. Everything auto-fixable has already been fixed;",
  "these are left deliberately rather than suppressed, because a suppressed warning is a lie",
  "that compiles.",
  "",
  `**Total outstanding: ${total}** · errors: ${errors} · generated by \`node scripts/build-warnings-backlog.mjs\` from a real ESLint run.`,
  "",
  "## How the count got here",
  "",
  "| Stage | Warnings |",
  "|---|---:|",
  "| Before | 2,424 |",
  "| After excluding gitignored snapshot copies (`.codex/`, `.claude/`) | 944 |",
  "| After `eslint --fix` | 231 |",
  "",
  "The first drop is a correction, not a fix. 1,478 warnings came from `.codex/` and `.claude/`,",
  "gitignored point-in-time snapshots of source. Linting them described copies of the code",
  "rather than the code — and `--fix` would have rewritten those snapshots, destroying the",
  "historical fidelity that is their only purpose.",
  "",
  "## Whose warnings are these?",
  "",
  "This repository ships four products. Splitting the backlog by owner changes what it means:",
  "",
  "| Owner | Warnings |",
  "|---|---:|",
  `| Workforce / dashboard / documents (outside OCADE scope) | **${otherProduct}** |`,
  `| OCADE and shared code | **${ocade}** |`,
  "",
  "Most outstanding `any` usage is in the bundled workforce product, not OCADE. That does not",
  "make it acceptable — it is employee and timesheet data flowing untyped — but OCADE's own",
  "type discipline is considerably better than the raw count suggests.",
  "",
];

for (const [rule, files] of [...byRule.entries()].sort((a, b) => countOf(b[1]) - countOf(a[1]))) {
  lines.push(`## \`${rule}\` — ${countOf(files)}`, "");
  lines.push(NOTES[rule] ?? "No note recorded — add one before this rule is actioned.", "");
  lines.push("| File | Count | Lines |", "|---|---:|---|");
  for (const [file, ls] of [...files.entries()].sort((a, b) => b[1].length - a[1].length)) {
    const shown = ls.slice(0, 12).join(", ") + (ls.length > 12 ? ` … +${ls.length - 12}` : "");
    lines.push(`| \`${file}\` | ${ls.length} | ${shown} |`);
  }
  lines.push("");
}

writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT} — ${total} warnings across ${byRule.size} rules, ${errors} errors.`);
