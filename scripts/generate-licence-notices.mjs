/**
 * Third-party licence notices.
 *
 * Specification §19.9 requires licence notices to be included, and §7.7/§19.10
 * require licence obligations to be satisfied. This was previously recorded as
 * externally blocked along with the rest of packaging — wrongly. Producing the
 * notices needs no installer, certificate or clean machine: the information is
 * in the dependency tree that is already on disk.
 *
 * Walks the PRODUCTION dependency closure (dependencies of dependencies, not
 * devDependencies), reads each package's licence declaration and licence text,
 * and writes release/THIRD_PARTY_NOTICES.md.
 *
 * HONESTY RULES:
 *  - A package whose licence cannot be determined is listed as UNKNOWN, never
 *    silently omitted and never guessed from a similar name.
 *  - A package with a copyleft or otherwise attention-worthy licence is called
 *    out in its own section so it cannot be lost in a long alphabetical list.
 *  - Licence TEXT is copied verbatim when the package ships it; when it does
 *    not, that is stated rather than substituting a canned template, because a
 *    canned MIT text is not the copyright holder's notice.
 *
 * Usage: node scripts/generate-licence-notices.mjs [--check]
 *   --check  verify the committed notices are current; exit 1 if stale.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const OUTPUT = "release/THIRD_PARTY_NOTICES.md";
const checkOnly = process.argv.includes("--check");

const rootPkg = JSON.parse(readFileSync("package.json", "utf8"));

/** Licences that need a human to look at them before shipping. */
const ATTENTION = /GPL|AGPL|LGPL|MPL|EPL|CDDL|SSPL|CC-BY-SA|OSL|EUPL/i;

function readPackage(dir) {
  const manifest = join(dir, "package.json");
  if (!existsSync(manifest)) return null;
  try {
    return JSON.parse(readFileSync(manifest, "utf8"));
  } catch {
    return null;
  }
}

function resolvePackageDir(name) {
  const direct = join("node_modules", ...name.split("/"));
  return existsSync(direct) ? direct : null;
}

/** Licence text shipped alongside the package, if any. */
function findLicenceText(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return null;
  }
  const file = entries.find((n) => /^(LICEN[CS]E|COPYING|NOTICE)(\.|$)/i.test(n));
  if (!file) return null;
  try {
    const text = readFileSync(join(dir, file), "utf8").trim();
    return text.length > 0 ? text : null;
  } catch {
    return null;
  }
}

function declaredLicence(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license === "object" && pkg.license.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses) && pkg.licenses[0]?.type) return pkg.licenses[0].type;
  return null;
}

// Walk the production closure breadth-first.
const seen = new Map();
const queue = Object.keys(rootPkg.dependencies ?? {});

while (queue.length > 0) {
  const name = queue.shift();
  if (seen.has(name)) continue;

  const dir = resolvePackageDir(name);
  if (!dir) {
    seen.set(name, { name, version: "unresolved", licence: null, text: null, dir: null });
    continue;
  }

  const pkg = readPackage(dir);
  if (!pkg) {
    seen.set(name, { name, version: "unreadable", licence: null, text: null, dir });
    continue;
  }

  seen.set(name, {
    name,
    version: pkg.version ?? "unknown",
    licence: declaredLicence(pkg),
    text: findLicenceText(dir),
    author: typeof pkg.author === "string" ? pkg.author : (pkg.author?.name ?? null),
    homepage: pkg.homepage ?? pkg.repository?.url ?? null,
    dir,
  });

  for (const dep of Object.keys(pkg.dependencies ?? {})) {
    if (!seen.has(dep)) queue.push(dep);
  }
}

const packages = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const unknown = packages.filter((p) => !p.licence);
const attention = packages.filter((p) => p.licence && ATTENTION.test(p.licence));
const withoutText = packages.filter((p) => p.licence && !p.text);

const byLicence = packages.reduce((acc, p) => {
  const key = p.licence ?? "UNKNOWN";
  (acc[key] ??= []).push(p);
  return acc;
}, {});

const lines = [];
lines.push("# Third-party licence notices");
lines.push("");
lines.push(
  `${rootPkg.name} v${rootPkg.version} bundles the production dependencies below. ` +
    "Generated by `node scripts/generate-licence-notices.mjs` from the installed " +
    "dependency tree — not hand-maintained, so it cannot drift from what actually ships.",
);
lines.push("");
lines.push(
  `**${packages.length} production packages** across ${Object.keys(byLicence).length} licence types.`,
);
lines.push("");

if (attention.length > 0) {
  lines.push("## Licences requiring review before distribution");
  lines.push("");
  lines.push(
    "These carry copyleft or reciprocal terms. They are called out here so they " +
      "cannot be lost in the alphabetical list below; a human must confirm the " +
      "obligations are met for the way this product is distributed.",
  );
  lines.push("");
  for (const p of attention) lines.push(`- **${p.name}@${p.version}** — ${p.licence}`);
  lines.push("");
}

if (unknown.length > 0) {
  lines.push("## Licence could not be determined");
  lines.push("");
  lines.push(
    "Listed rather than omitted or guessed. Each needs a human to check the " +
      "upstream project before distribution.",
  );
  lines.push("");
  for (const p of unknown) lines.push(`- ${p.name}@${p.version}`);
  lines.push("");
}

lines.push("## Summary by licence");
lines.push("");
for (const [licence, list] of Object.entries(byLicence).sort()) {
  lines.push(`- **${licence}** — ${list.length} package${list.length === 1 ? "" : "s"}`);
}
lines.push("");

lines.push("## Packages");
lines.push("");
for (const p of packages) {
  lines.push(`### ${p.name}@${p.version}`);
  lines.push("");
  lines.push(`- Licence: ${p.licence ?? "**UNKNOWN — needs review**"}`);
  if (p.author) lines.push(`- Author: ${p.author}`);
  if (p.homepage) lines.push(`- Homepage: ${String(p.homepage).replace(/^git\+/, "")}`);
  lines.push("");
  if (p.text) {
    lines.push("<details><summary>Licence text as shipped by the package</summary>");
    lines.push("");
    lines.push("```text");
    lines.push(p.text.slice(0, 12000));
    lines.push("```");
    lines.push("");
    lines.push("</details>");
  } else {
    // Deliberately not substituting a canned template: a generic MIT body is
    // not this copyright holder's notice.
    lines.push(
      "_This package ships no licence file. The declared licence above is from " +
        "its package manifest; obtain the full text from the upstream project._",
    );
  }
  lines.push("");
}

const output = lines.join("\n") + "\n";

/**
 * Compare content, not line endings.
 *
 * `output` is always built with "\n", but this repository has
 * `core.autocrlf=true` and no `.gitattributes`, so git hands every fresh
 * checkout a CRLF copy of the committed file. A raw `!==` therefore reported
 * the notices as stale on every machine except one that happened to have LF
 * on disk — 581,050 bytes here against 595,017 in a clean clone, identical
 * once newlines are normalised. That failed the `licences:check` step of the
 * CI web job on every run while passing locally.
 *
 * Normalising both sides keeps the check meaningful: it still fails when a
 * dependency's licence actually changes, which is the only thing it is for.
 */
const normalizeNewlines = (text) => text.replace(/\r\n/g, "\n");

if (checkOnly) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (normalizeNewlines(current) !== normalizeNewlines(output)) {
    console.error(`${OUTPUT} is stale. Run \`npm run licences:generate\` and commit the result.`);
    process.exit(1);
  }
  console.log(`Licence notices are current: ${packages.length} production packages.`);
} else {
  writeFileSync(OUTPUT, output);
  console.log(`Wrote ${OUTPUT}: ${packages.length} production packages.`);
  console.log(`  licence types: ${Object.keys(byLicence).length}`);
  console.log(`  needing review: ${attention.length}`);
  console.log(`  undetermined: ${unknown.length}`);
  console.log(`  no shipped text: ${withoutText.length}`);
}
