/**
 * The remaining-gap ledger PLAN.md §P asks for, written from one source.
 *
 * WHY GENERATED. §P asks for the ledger in two formats and then adds "generate
 * Markdown from JSON" and "fail verification for a stale generated report".
 * Both exist for the same reason a report that can drift from its source is a
 * claim rather than a record: the moment somebody edits the Markdown by hand,
 * the two disagree and neither can be trusted.
 *
 * So `src/lib/release/remaining-gaps.ts` is the only place a gap is written
 * down, this produces both files from it, and `--check` regenerates and
 * compares byte-for-byte. The validation rules live beside the data, typed and
 * unit-tested, rather than in this script — a generator that also decides what
 * is valid tends to grow a second, weaker opinion.
 *
 * Usage: vite-node scripts/generate-remaining-gaps.mjs [--check]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REMAINING_PRODUCT_GAPS, validateGapLedger } from "../src/lib/release/remaining-gaps.ts";

const CHECK = process.argv.includes("--check");
const DIRECTORY = join("release", "checklists");
const JSON_PATH = join(DIRECTORY, "OCADE_REMAINING_PRODUCT_GAPS.json");
const MARKDOWN_PATH = join(DIRECTORY, "OCADE_REMAINING_PRODUCT_GAPS.md");

const problems = validateGapLedger(REMAINING_PRODUCT_GAPS, (path) => existsSync(path));
if (problems.length > 0) {
  console.error("The remaining-gap ledger does not satisfy PLAN.md §P:");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const byStatus = (status) => REMAINING_PRODUCT_GAPS.filter((gap) => gap.status === status);

/*
 * The counts a reader actually needs, and the one the final gate turns on.
 *
 * `applicableMissing` excludes NOT-APPLICABLE deliberately: PLAN.md §P's gate
 * is "zero applicable MISSING", and rolling a genuinely inapplicable
 * requirement into that number would make the gate impossible to pass for a
 * reason that says nothing about the product.
 */
const summary = {
  total: REMAINING_PRODUCT_GAPS.length,
  missing: byStatus("MISSING").length,
  implemented: byStatus("IMPLEMENTED").length,
  tested: byStatus("TESTED").length,
  runtimeProven: byStatus("RUNTIME-PROVEN").length,
  externallyBlocked: byStatus("EXTERNALLY-BLOCKED").length,
  notApplicable: byStatus("NOT-APPLICABLE").length,
};
summary.applicableMissing = summary.missing;

const document = {
  generatedBy: "scripts/generate-remaining-gaps.mjs",
  source: "src/lib/release/remaining-gaps.ts",
  authority: "PLAN.md §P",
  summary,
  gaps: REMAINING_PRODUCT_GAPS,
};

const jsonText = `${JSON.stringify(document, null, 2)}\n`;

const escapeCell = (value) => String(value).replace(/\|/g, "\\|").replace(/\n+/g, " ");
const list = (values) => (values.length ? values.map((value) => `\`${value}\``).join(", ") : "—");

const markdownText = [
  "# OCADE remaining product gaps",
  "",
  "> Generated by `scripts/generate-remaining-gaps.mjs` from",
  "> `src/lib/release/remaining-gaps.ts`. Do not edit this file; edit the source",
  "> and regenerate. `npm run gaps:check` fails when the two disagree.",
  "",
  "Authority: `PLAN.md` §P.",
  "",
  "## Summary",
  "",
  "| Status | Count |",
  "| --- | --- |",
  `| MISSING (applicable) | ${summary.applicableMissing} |`,
  `| IMPLEMENTED | ${summary.implemented} |`,
  `| TESTED | ${summary.tested} |`,
  `| RUNTIME-PROVEN | ${summary.runtimeProven} |`,
  `| EXTERNALLY-BLOCKED | ${summary.externallyBlocked} |`,
  `| NOT-APPLICABLE | ${summary.notApplicable} |`,
  `| **Total** | **${summary.total}** |`,
  "",
  "## Gaps",
  "",
  ...REMAINING_PRODUCT_GAPS.flatMap((gap) => [
    `### ${gap.id} — ${escapeCell(gap.area)}`,
    "",
    `- **Status**: ${gap.status}`,
    `- **Disposition**: ${gap.disposition}`,
    `- **Requirement**: ${escapeCell(gap.requirement)}`,
    `- **Discovered from**: ${escapeCell(gap.discoveredFrom)}`,
    `- **Existing authority**: ${gap.existingAuthority ? `\`${gap.existingAuthority}\`` : "none"}`,
    `- **Implementation evidence**: ${list(gap.implementationEvidence)}`,
    `- **Test evidence**: ${list(gap.testEvidence)}`,
    `- **Runtime evidence**: ${list(gap.runtimeEvidence)}`,
    ...(gap.externalBlocker
      ? [
          `- **External dependency**: ${escapeCell(gap.externalBlocker.dependency)}`,
          `- **Exact reason**: ${escapeCell(gap.externalBlocker.exactReason)}`,
          `- **Repository work complete**: ${gap.externalBlocker.repositoryWorkComplete ? "yes" : "no"}`,
          `- **Interface verified as unavailable**: ${gap.externalBlocker.unavailableUiVerified ? "yes" : "no"}`,
        ]
      : []),
    `- **Last verified**: ${gap.lastVerifiedAt}`,
    "",
  ]),
].join("\n");

if (CHECK) {
  const stale = [];
  for (const [path, expected] of [
    [JSON_PATH, jsonText],
    [MARKDOWN_PATH, markdownText],
  ]) {
    if (!existsSync(path)) {
      stale.push(`${path} is missing`);
      continue;
    }
    if (readFileSync(path, "utf8") !== expected) stale.push(`${path} is stale`);
  }
  if (stale.length > 0) {
    console.error("The remaining-gap ledger is out of date:");
    for (const entry of stale) console.error(`  - ${entry}`);
    console.error("Run `npm run gaps:generate`.");
    process.exit(1);
  }
  console.log(
    `Remaining-gap ledger current: ${summary.total} gaps, ${summary.applicableMissing} applicable MISSING.`,
  );
} else {
  mkdirSync(DIRECTORY, { recursive: true });
  writeFileSync(JSON_PATH, jsonText, "utf8");
  writeFileSync(MARKDOWN_PATH, markdownText, "utf8");
  console.log(`Wrote ${JSON_PATH} and ${MARKDOWN_PATH} (${summary.total} gaps).`);
}
