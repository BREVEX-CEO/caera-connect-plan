import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { execFile } from "node:child_process";
import { mkdtemp, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import {
  VIDEO_PACK,
  captionsAvailable,
  probeVideo,
  trimVideo,
  cropVideo,
  captionVideo,
  parseProbe,
  escapeDrawText,
  type VideoRunner,
} from "../skills/packs/video-pack";

/**
 * REAL VIDEO EDITING, WITH A REAL ENCODER.
 *
 * A video is generated, trimmed, cropped, captioned, exported and then DECODED
 * AGAIN — because a file that ffmpeg wrote and nothing can play is the failure
 * this pack exists to catch, and an exit code cannot tell the two apart.
 *
 * The runner is the same injected shape `archive-pack` uses for tar. Here it
 * runs the ffmpeg binary that ships with `ffmpeg-static`, so what is exercised
 * is the encoder the product would drive, not a description of one.
 */

// eslint-disable-next-line @typescript-eslint/no-require-imports
const ffmpegPath: string | null = (() => {
  try {
    return require("ffmpeg-static") as string;
  } catch {
    return null;
  }
})();
/*
 * ffprobe ships SEPARATELY from ffmpeg-static, which does not include it. The
 * first version of this file assumed it sat beside the encoder, fell back to a
 * bare "ffprobe" that was not on PATH either, and every editing test then
 * returned early on a `probeWorks` flag and passed without doing anything.
 * A vacuous pass is worse than a failure, so the binary is resolved properly
 * and its absence is asserted below rather than silently skipped.
 */
// eslint-disable-next-line @typescript-eslint/no-require-imports
const ffprobePath: string | null = (() => {
  try {
    return (require("ffprobe-static") as { path: string }).path;
  } catch {
    return null;
  }
})();

const runReal: VideoRunner = (cmd) =>
  new Promise((resolve) => {
    const bin = cmd.bin === "ffmpeg" ? (ffmpegPath ?? "ffmpeg") : (ffprobePath ?? "ffprobe");
    execFile(
      bin,
      cmd.args,
      { cwd: cmd.cwd, maxBuffer: 16 * 1024 * 1024 },
      (error, stdout, stderr) => {
        resolve({ ok: !error, stdout: stdout ?? "", stderr: stderr ?? "", code: error ? 1 : 0 });
      },
    );
  });

let probeWorks = false;
let dir = "";
const SOURCE = "source.mp4";

beforeAll(async () => {
  if (!ffmpegPath) return;
  dir = await mkdtemp(join(tmpdir(), "ocade-video-"));
  // A real 3-second 320x240 clip, generated by the encoder itself.
  await runReal({
    bin: "ffmpeg",
    args: [
      "-y",
      "-f",
      "lavfi",
      "-i",
      "testsrc=size=320x240:rate=15:duration=3",
      "-c:v",
      "libx264",
      "-preset",
      "ultrafast",
      "-pix_fmt",
      "yuv420p",
      "--",
      SOURCE,
    ],
    cwd: dir,
  });
  const probe = await probeVideo(runReal, dir, SOURCE);
  probeWorks = probe.ok;
}, 120_000);

afterAll(async () => {
  if (dir) await rm(dir, { recursive: true, force: true });
});

describe("the pack describes itself honestly", () => {
  it("marks every editing capability as mutating and file-verified", () => {
    for (const capability of VIDEO_PACK.capabilities) {
      if (capability.mutating) expect(capability.verifyBy).toBe("file");
    }
  });

  it("does not claim work it does not do", () => {
    expect(VIDEO_PACK.coverageNote).toMatch(
      /does not composite|colour-grade|drives no third-party/i,
    );
  });
});

describe("drawtext escaping", () => {
  it("escapes the characters that would truncate a caption", () => {
    // "12:30" losing everything after the colon is the bug this prevents.
    expect(escapeDrawText("12:30")).toBe("12\\:30");
    expect(escapeDrawText("it's")).toBe("it\\'s");
    expect(escapeDrawText("100%")).toBe("100\\%");
  });
});

describe("probe output", () => {
  it("reports a file with no video track rather than inventing dimensions", () => {
    const facts = parseProbe(
      JSON.stringify({ format: { duration: "5" }, streams: [{ codec_type: "audio" }] }),
    );
    expect(facts?.hasVideoTrack).toBe(false);
    expect(facts?.width).toBe(0);
  });

  it("returns null for output that is not JSON at all", () => {
    expect(parseProbe("ffprobe: command not found")).toBeNull();
  });
});

const toolsReady = Boolean(ffmpegPath) && Boolean(ffprobePath);

describe("the encoder and the prober are both present", () => {
  it("resolves both binaries, so nothing below can pass by skipping", () => {
    expect(ffmpegPath, "ffmpeg-static did not resolve").toBeTruthy();
    expect(ffprobePath, "ffprobe-static did not resolve").toBeTruthy();
    expect(existsSync(ffmpegPath!)).toBe(true);
    expect(existsSync(ffprobePath!)).toBe(true);
  });
});

describe.runIf(toolsReady)("a real video is imported, edited, exported and replayed", () => {
  it("probed the generated source, so every case below did real work", () => {
    expect(
      probeWorks,
      "the source clip could not be probed; the edits below would be vacuous",
    ).toBe(true);
  });

  it("imports the source and reads its real duration and size", async () => {
    const result = await probeVideo(runReal, dir, SOURCE);
    expect(result.ok, "reason" in result ? result.reason : "").toBe(true);
    if (!result.ok) throw new Error("unreachable");
    expect(result.data.width).toBe(320);
    expect(result.data.height).toBe(240);
    expect(result.data.durationSeconds).toBeGreaterThan(2.5);
  }, 120_000);

  it("TRIMS to a shorter span, and proves the result is shorter", async () => {
    const out = "trimmed.mp4";
    const result = await trimVideo(runReal, dir, SOURCE, out, {
      startSeconds: 1,
      durationSeconds: 1,
    });
    expect(result.ok, "reason" in result ? result.reason : "").toBe(true);
    if (!result.ok) throw new Error("unreachable");
    expect(result.data.durationSeconds).toBeGreaterThan(0.5);
    expect(result.data.durationSeconds).toBeLessThan(1.6);
    expect((await stat(join(dir, out))).size).toBeGreaterThan(0);
  }, 120_000);

  it("CROPS to a smaller rectangle, and proves the frame really shrank", async () => {
    const out = "cropped.mp4";
    const result = await cropVideo(runReal, dir, SOURCE, out, {
      x: 20,
      y: 20,
      width: 160,
      height: 120,
    });
    expect(result.ok, "reason" in result ? result.reason : "").toBe(true);
    if (!result.ok) throw new Error("unreachable");
    expect(result.data.width).toBe(160);
    expect(result.data.height).toBe(120);
  }, 120_000);

  /**
   * `drawtext` needs libfreetype and many static ffmpeg builds omit it — this
   * one does. So the assertion is conditional on what the ENCODER can do: burn
   * the caption in where the filter exists, and refuse in a sentence the person
   * can act on where it does not. What is never acceptable is "Filter not
   * found" reaching the user, or a caption silently not being drawn.
   */
  it("CAPTIONS where the encoder can, and says why plainly where it cannot", async () => {
    const out = "captioned.mp4";
    const available = await captionsAvailable(runReal, dir);
    const result = await captionVideo(runReal, dir, SOURCE, out, "Recorded at 12:30 — it's fine");

    if (available) {
      expect(result.ok, "reason" in result ? result.reason : "").toBe(true);
      if (!result.ok) throw new Error("unreachable");
      expect(result.data.width).toBe(320);
      expect(result.data.height).toBe(240);
    } else {
      expect(result.ok).toBe(false);
      if (result.ok) throw new Error("unreachable");
      expect(result.reason).toMatch(/built without the text filter|libfreetype/i);
      expect(result.reason).toMatch(/trimming and cropping still work/i);
      expect(result.reason).not.toMatch(/filter not found/i);
    }
  }, 120_000);

  /**
   * THE ONE THAT MATTERS. ffmpeg exits 0 on files nothing can play. Decoding
   * the export to raw frames is the difference between "it wrote something"
   * and "it wrote a video".
   */
  it("REPLAYS the exported file by decoding every frame of it", async () => {
    const out = "export.mp4";
    const edited = await trimVideo(runReal, dir, SOURCE, out, {
      startSeconds: 0.5,
      durationSeconds: 1.5,
    });
    expect(edited.ok).toBe(true);

    const decoded = await runReal({
      bin: "ffmpeg",
      args: ["-v", "error", "-i", out, "-f", "null", "-"],
      cwd: dir,
    });
    expect(decoded.ok, `decoding failed: ${decoded.stderr}`).toBe(true);
    // `-v error` prints nothing when every frame decoded cleanly.
    expect(decoded.stderr.trim()).toBe("");
  }, 120_000);

  it("REFUSES a trim that starts past the end, rather than writing an empty file", async () => {
    const result = await trimVideo(runReal, dir, SOURCE, "past-end.mp4", {
      startSeconds: 99,
      durationSeconds: 1,
    });
    expect(result.ok).toBe(false);
  }, 120_000);

  it("REFUSES a crop that reaches outside the frame", async () => {
    const result = await cropVideo(runReal, dir, SOURCE, "too-big.mp4", {
      x: 0,
      y: 0,
      width: 9999,
      height: 9999,
    });
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error("unreachable");
    expect(result.reason).toMatch(/outside the .* frame/i);
  }, 120_000);

  it("REFUSES a path ffmpeg would read as an option", async () => {
    const result = await trimVideo(runReal, dir, "-i", "out.mp4", {
      startSeconds: 0,
      durationSeconds: 1,
    });
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error("unreachable");
    expect(result.reason).toMatch(/read as an option/i);
  }, 60_000);

  /**
   * ffmpeg decodes a PLAIN TEXT FILE as "ANSI art": notes.txt comes back as a
   * 640x400 video in the `tty` container with a real duration. A demuxer that
   * can render anything is not a reason to treat anything as a video.
   */
  it("refuses a text file even though the decoder calls it a video", async () => {
    await writeFile(join(dir, "notes.txt"), "this is not a video", "utf8");
    const result = await probeVideo(runReal, dir, "notes.txt");
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error("unreachable");
    expect(result.reason).toMatch(/not a video/i);
  }, 60_000);
});
