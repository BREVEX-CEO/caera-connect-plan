import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

/**
 * Third-party licence notices (spec §19.9 "licence notices are included").
 *
 * This was previously recorded as externally blocked along with the rest of
 * packaging. That was wrong: producing the notices needs no installer,
 * certificate or clean machine — the information is in the dependency tree
 * already on disk. Correcting an over-blocked item is itself a fix, because an
 * inaccurate readiness claim is a defect.
 *
 * The notices are GENERATED, never hand-maintained, so they cannot drift from
 * what actually ships; CI fails if the committed file is stale.
 */

const NOTICES = "release/THIRD_PARTY_NOTICES.md";
const notices = readFileSync(NOTICES, "utf8");
const pkg = JSON.parse(readFileSync("package.json", "utf8")) as {
  scripts: Record<string, string>;
  dependencies: Record<string, string>;
};

describe("the notices cover what actually ships", () => {
  it("lists a realistic number of production packages", () => {
    const m = /\*\*(\d+) production packages\*\*/.exec(notices);
    expect(m).not.toBeNull();
    expect(Number(m![1])).toBeGreaterThan(100);
  });

  it("includes every DIRECT production dependency by name", () => {
    const missing = Object.keys(pkg.dependencies).filter(
      (name) => !notices.includes(`### ${name}@`),
    );
    expect(missing, `not in notices: ${missing.join(", ")}`).toEqual([]);
  });

  it("covers transitive dependencies too, not just the direct ones", () => {
    const entries = (notices.match(/^### /gm) ?? []).length;
    expect(entries).toBeGreaterThan(Object.keys(pkg.dependencies).length);
  });

  it("names a licence for every entry", () => {
    // "UNKNOWN — needs review" is acceptable and honest; a MISSING line is not.
    const entries = (notices.match(/^### /gm) ?? []).length;
    const licences = (notices.match(/^- Licence: /gm) ?? []).length;
    expect(licences).toBe(entries);
  });
});

describe("attention-worthy licences are surfaced, not buried", () => {
  it("has a dedicated review section", () => {
    expect(notices).toMatch(/## Licences requiring review before distribution/);
  });

  it("flags the copyleft and reciprocal licences present in the tree", () => {
    // A weak-copyleft dependency in a distributed desktop product is exactly
    // the thing that must not be discovered after shipping.
    const section = notices.slice(
      notices.indexOf("## Licences requiring review"),
      notices.indexOf("## Summary by licence"),
    );
    expect(section).toMatch(/MPL-2\.0|GPL/);
  });

  it("does not silently omit a package whose licence is undetermined", () => {
    if (notices.includes("## Licence could not be determined")) {
      const section = notices.slice(notices.indexOf("## Licence could not be determined"));
      expect(section).toMatch(/needs? (a )?human|review/i);
    }
    // Either way, no entry may lack the Licence line — asserted above.
    expect(notices).not.toMatch(/^- Licence:\s*$/m);
  });
});

describe("the notices are honest about what they contain", () => {
  it("says it is generated rather than hand-maintained", () => {
    expect(notices).toMatch(/Generated by `node scripts\/generate-licence-notices\.mjs`/);
  });

  it("does not substitute a canned licence body for a missing one", () => {
    // A generic MIT text is not the copyright holder's notice.
    expect(notices).toMatch(/ships no licence file/);
    expect(notices).toMatch(/obtain the full text from the upstream project/i);
  });

  it("quotes shipped licence text verbatim in a collapsible block", () => {
    expect(notices).toMatch(/Licence text as shipped by the package/);
  });
});

describe("the notices cannot go stale", () => {
  it("is regenerated by a script, and --check reports it current", () => {
    const out = execFileSync(
      process.execPath,
      ["scripts/generate-licence-notices.mjs", "--check"],
      { encoding: "utf8" },
    );
    expect(out).toMatch(/current/);
  });

  it("is exposed as npm scripts", () => {
    expect(pkg.scripts["licences:generate"]).toContain("generate-licence-notices.mjs");
    expect(pkg.scripts["licences:check"]).toContain("--check");
  });

  it("is enforced in CI, so a dependency change without regeneration fails", () => {
    const ci = readFileSync(".github/workflows/ci.yml", "utf8");
    const parity = readFileSync("scripts/verify-full.mjs", "utf8");
    expect(ci).toContain("npm run verify:full");
    expect(parity).toContain('"licences:check"');
  });
});
