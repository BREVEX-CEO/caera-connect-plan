import { Cpu, HardDrive, MemoryStick, MonitorCog, AlertTriangle } from "lucide-react";
import { PageHeader } from "@/components/shell/PageHeader";
import { GlassPanel } from "@/components/shell/GlassPanel";
import { StatusBadge } from "@/components/shell/StatusBadge";
import { LocalEngineControl } from "@/components/ocade/LocalEngineControl";
import { LocalModelLifecyclePanel } from "@/components/ocade/LocalModelLifecyclePanel";
import { useDevicePolicy, describeDeviceSource } from "@/lib/use-device-policy";
import { PairedComputerPanel } from "@/components/settings/PairedComputerPanel";

/**
 * OCADE Local Engine settings.
 *
 * The engine controls and the model lifecycle already existed on the model
 * control centre; what did not exist anywhere was a plain answer to the
 * question a user actually asks first — "what did OCADE decide about MY
 * computer, and why?".
 *
 * The specification is measured, not typed: every figure below comes from the
 * hardware probe on this machine, and the sentence explaining the choice is
 * generated by the same tier policy that made it. When measurement fails, the
 * page says so and shows what it is falling back to, because "we could not
 * measure this device" and "this device is weak" are different facts and lead
 * to different actions.
 *
 * The raw model name is deliberately absent from this page. It belongs in
 * About and Licences, where the licence it ships under is also shown.
 */

function Spec({
  icon: Icon,
  label,
  value,
  hint,
}: {
  icon: typeof Cpu;
  label: string;
  value: string;
  hint?: string;
}) {
  return (
    <div className="rounded-md border border-white/10 bg-white/[0.02] p-3">
      <div className="flex items-center gap-2 text-[11px] uppercase tracking-[0.12em] text-muted-foreground">
        <Icon className="h-3.5 w-3.5" />
        {label}
      </div>
      <div className="mt-1 text-sm font-medium text-foreground">{value}</div>
      {hint ? <div className="mt-0.5 text-[12px] text-muted-foreground">{hint}</div> : null}
    </div>
  );
}

export function LocalEngineSettingsPanel() {
  const device = useDevicePolicy();
  const profile = device.profile;

  return (
    <>
      <PageHeader
        eyebrow="OCADE"
        title="Local Engine"
        description="The AI engine that runs on this computer. It answers without sending anything to a server, and it is bound to this machine only."
        actions={
          device.loading ? (
            <StatusBadge status="pending">Measuring device</StatusBadge>
          ) : device.measured ? (
            <StatusBadge status="active">Device measured</StatusBadge>
          ) : (
            <StatusBadge status="setup_required">Estimated in browser</StatusBadge>
          )
        }
      />

      <div className="grid gap-5 pb-16">
        <GlassPanel className="p-5">
          <h2 className="text-sm font-semibold text-foreground">This device</h2>

          {device.problem ? (
            <div className="mt-3 flex gap-3 rounded-md border border-[color:var(--state-warning)]/30 bg-[color:var(--state-warning)]/5 p-3 text-[13px]">
              <AlertTriangle className="h-4 w-4 shrink-0 text-[color:var(--state-warning)]" />
              <p className="text-muted-foreground">{device.problem}</p>
            </div>
          ) : null}

          {profile ? (
            <>
              <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
                <Spec
                  icon={MemoryStick}
                  label="Memory"
                  /*
                   * A browser reports memory CAPPED AT 8 GiB, so on an estimate
                   * this is a floor and has to read like one. "8 GB total" on a
                   * 16 GB laptop is a wrong fact, not a rounded one.
                   */
                  value={
                    device.measured
                      ? `${profile.totalRamGib} GB total`
                      : profile.totalRamGib > 0
                        ? `at least ${profile.totalRamGib} GB`
                        : "not reported"
                  }
                  hint={
                    device.measured
                      ? `${profile.availableRamGib} GB free right now`
                      : "Browsers cap this figure, so OCADE does not use it to rule engines out."
                  }
                />
                <Spec icon={Cpu} label="Processor" value={`${profile.cpuCount} logical cores`} />
                <Spec
                  icon={MonitorCog}
                  label="Graphics"
                  value={
                    profile.hasDiscreteGpu
                      ? "Dedicated graphics"
                      : profile.gpuCertain
                        ? "No dedicated graphics"
                        : "Could not be confirmed"
                  }
                  hint={
                    profile.gpuCertain
                      ? undefined
                      : "OCADE does not assume acceleration it could not verify."
                  }
                />
                <Spec
                  icon={HardDrive}
                  label="Free storage"
                  value={`${profile.freeStorageGib} GB`}
                />
              </div>

              {device.because ? (
                <div className="mt-4 rounded-md border border-white/10 bg-white/[0.02] p-3">
                  <div className="text-[11px] uppercase tracking-[0.12em] text-muted-foreground">
                    Why this engine
                  </div>
                  <p className="mt-1 text-[13px] text-muted-foreground">{device.because}</p>
                </div>
              ) : null}
            </>
          ) : (
            <p className="mt-3 text-[13px] text-muted-foreground">
              {device.loading
                ? "Reading this device's memory, processor, graphics and free storage…"
                : "This device could not be measured, so engine selection is running on a browser estimate. Memory-based limits are relaxed rather than guessed at."}
            </p>
          )}

          <p className="mt-4 text-[12px] text-muted-foreground">{describeDeviceSource(device)}</p>

          <p className="mt-2 text-[12px] text-muted-foreground">
            Memory limits are measured against TOTAL memory, not the amount free at this instant.
            Free memory moves constantly as the system releases cache, and selecting on it would
            refuse engines this machine demonstrably runs.
          </p>
        </GlassPanel>

        <GlassPanel className="p-5">
          {/*
            Start/stop comes first: installing or activating a model against a
            runtime that is not listening fails for a reason the download UI
            cannot show.
          */}
          <LocalEngineControl />
          <div className="mt-5" />
          <LocalModelLifecyclePanel />
        </GlassPanel>

        <PairedComputerPanel />

        <GlassPanel className="p-5">
          <h2 className="text-sm font-semibold text-foreground">Keeping this computer usable</h2>
          <ul className="mt-2 list-disc space-y-1 pl-5 text-[13px] text-muted-foreground">
            <li>
              One engine is held in memory at a time. A second resident model on a machine this size
              makes the system swap, which freezes whatever you are doing rather than merely slowing
              the reply.
            </li>
            <li>
              One request is served at a time. Parallel slots multiply memory use for no benefit
              when one person is chatting.
            </li>
            <li>
              Memory is released after a short idle period, so closing the chat gives it back.
            </li>
            <li>
              The engine listens on this computer only. It is never reachable from your network or
              the internet.
            </li>
          </ul>
        </GlassPanel>
      </div>
    </>
  );
}
