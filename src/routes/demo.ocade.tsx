import { createFileRoute } from "@tanstack/react-router";
import { useMemo, useState } from "react";
import { Link } from "@tanstack/react-router";
import { Cpu, Settings2, FolderOpen, Files, ArrowLeft } from "lucide-react";
import { useDemo } from "@/lib/demo/context";
import { ChatShell } from "@/components/ocade/chat/ChatShell";
import { ChatSidebar } from "@/components/ocade/chat/ChatSidebar";
import { MessageList } from "@/components/ocade/chat/MessageList";
import { ChatComposer } from "@/components/ocade/chat/ChatComposer";
import { ChatEmptyState } from "@/components/ocade/chat/ChatEmptyState";
import { EngineBadge } from "@/components/ocade/chat/EngineBadge";
import type {
  ChatConversationView,
  ChatMessageView,
  EngineStatusView,
} from "@/components/ocade/chat/chat-types";

export const Route = createFileRoute("/demo/ocade")({
  head: () => ({
    meta: [{ title: "OCADE demo — CAERA CADANE" }],
  }),
  component: DemoOcade,
});

/**
 * The public OCADE demo.
 *
 * Runs on the SAME chat components as the signed-in product, deliberately.
 * A demo built from its own throwaway markup drifts from the real thing within
 * weeks and ends up advertising an interface that no longer exists. Sharing the
 * components means what a visitor sees here is what they get.
 *
 * WHAT IS DIFFERENT, AND SAID OUT LOUD: no model runs. Replies are canned and
 * labelled as canned, every time, because a demo that lets someone believe they
 * spoke to the AI is a lie with a signup attached.
 */

const DEMO_REPLY =
  "This is the OCADE demo, so no model is running and this reply is canned — I have not read your message.\n\nIn the real product this answer would be generated by **OCADE Local**, on your own computer, with nothing sent to a server. Sign in to set that up; OCADE picks an engine that suits your device and fetches it in the background.";

const DEMO_CONVERSATIONS: ChatConversationView[] = [
  { id: "demo-1", title: "Quarterly summary from a PDF", updatedAt: new Date().toISOString() },
  {
    id: "demo-2",
    title: "Explain this stack trace",
    updatedAt: new Date(Date.now() - 26 * 60 * 60 * 1000).toISOString(),
  },
  {
    id: "demo-3",
    title: "Rewrite onboarding email",
    updatedAt: new Date(Date.now() - 4 * 24 * 60 * 60 * 1000).toISOString(),
  },
  {
    id: "demo-4",
    title: "Reading a dashboard screenshot",
    updatedAt: new Date(Date.now() - 20 * 24 * 60 * 60 * 1000).toISOString(),
  },
];

const DEMO_ENGINE: EngineStatusView = {
  locality: "unknown",
  label: "Demo — no engine",
  online: true,
  detail: "Nothing is generating these replies. Sign in to run OCADE Local on your own device.",
};

function DemoOcade() {
  const { state, addOcadeMessage } = useDemo();
  const [draft, setDraft] = useState("");
  const [activeId, setActiveId] = useState<string>("demo-1");

  const messages: ChatMessageView[] = useMemo(
    () =>
      state.ocadeMessages.map((m, index) => ({
        id: `demo-msg-${index}`,
        role: m.role,
        content: m.content,
        createdAt: new Date(
          Date.now() - (state.ocadeMessages.length - index) * 60_000,
        ).toISOString(),
        engineLabel: m.role === "assistant" ? "Demo reply" : undefined,
      })),
    [state.ocadeMessages],
  );

  function send() {
    const text = draft.trim();
    if (!text) return;
    addOcadeMessage("user", text);
    addOcadeMessage("assistant", DEMO_REPLY);
    setDraft("");
  }

  return (
    <ChatShell
      sidebar={
        <ChatSidebar
          conversations={DEMO_CONVERSATIONS}
          activeId={activeId}
          onSelect={setActiveId}
          onNewChat={() => setActiveId("demo-1")}
          footer={
            <div className="grid gap-0.5">
              <DemoNavRow icon={FolderOpen} label="Projects" />
              <DemoNavRow icon={Files} label="Files" />
              <DemoNavRow icon={Cpu} label="Models" />
              <DemoNavRow icon={Settings2} label="Settings" />
              {/*
                The chat shell owns the viewport, so this route cannot sit
                inside DemoShell without two competing scroll containers. That
                would have stranded a visitor with no way back to the rest of
                the demo, so the way out is here instead.
              */}
              <Link
                to="/demo"
                className="mt-1 flex items-center gap-2 rounded-lg px-2 py-1.5 text-[13px] text-muted-foreground transition hover:bg-accent hover:text-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
              >
                <ArrowLeft className="h-3.5 w-3.5 shrink-0" aria-hidden />
                Back to demo overview
              </Link>
            </div>
          }
        />
      }
      header={
        <div className="flex min-w-0 items-center gap-2">
          <span className="truncate text-[14px] font-medium text-foreground">
            {DEMO_CONVERSATIONS.find((c) => c.id === activeId)?.title ?? "New chat"}
          </span>
          <EngineBadge status={DEMO_ENGINE} className="ml-auto shrink-0" />
        </div>
      }
      banner={
        <div className="rounded-xl border border-[color:var(--state-warning)]/30 bg-[color:var(--state-warning)]/5 px-3.5 py-2.5 text-[12.5px] text-muted-foreground">
          <span className="font-medium text-foreground">Demo.</span> No model is running and replies
          are canned.{" "}
          <Link to="/auth" className="text-primary underline underline-offset-4">
            Sign in
          </Link>{" "}
          to run OCADE privately on your own device.
        </div>
      }
      composer={
        <ChatComposer
          value={draft}
          onChange={setDraft}
          onSubmit={send}
          engine={DEMO_ENGINE}
          placeholder="Try the interface — replies are canned in the demo…"
          imageDisabledReason="Attachments are disabled in the demo. Sign in to attach files and images."
        />
      }
    >
      <MessageList
        messages={messages}
        actions={{
          onCopy: () => {
            /* MessageBubble owns the clipboard write and its own feedback. */
          },
        }}
        emptyState={
          <ChatEmptyState
            greeting="OCADE, running privately."
            privacyLine="In the real product OCADE answers on your own computer. This demo shows the interface only."
            onPick={setDraft}
          />
        }
      />
    </ChatShell>
  );
}

function DemoNavRow({ icon: Icon, label }: { icon: typeof Cpu; label: string }) {
  return (
    <span
      className="flex cursor-not-allowed items-center gap-2 rounded-lg px-2 py-1.5 text-[13px] text-muted-foreground/60"
      title={`${label} is available after sign-in.`}
    >
      <Icon className="h-3.5 w-3.5 shrink-0" aria-hidden />
      {label}
      <span className="ml-auto text-[10px] uppercase tracking-wide">Sign in</span>
    </span>
  );
}
